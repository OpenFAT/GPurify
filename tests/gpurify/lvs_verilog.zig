//! LVS-075: structural Verilog tops over a SPICE cell library, as
//! exhaustive fixtures. Ported from tests/exhaustive/lvs.rs
//! (`verilog_tops`; `VerilogTop`'s Netgen-only fields, the library and the
//! Verilog with a `sub` port, stay with the skipped Netgen differential).
//!
//! Contents:
//! - `pub fn fixturesInto(arena: Allocator, depth: Depth, out: *std.ArrayList(Fixture)) !void`

const std = @import("std");
const Allocator = std.mem.Allocator;
const harness = @import("harness.zig");
const Depth = harness.Depth;
const Fixture = harness.Fixture;
const circuit = @import("lvs_circuit.zig");
const Dev = circuit.Dev;
const Circuit = circuit.Circuit;
const oracle = @import("lvs_oracle.zig");
const lf = @import("lvs_fixture.zig");

/// LVS-075: a drawn chain of two inverters against a Verilog top placing
/// the SPICE cell `BLK` (an inverter, ports `n0` in, `n1` out, `n2` and
/// `n3` its rails) twice, by name and in order, and through a bus and an
/// `assign`; and two faults, the second inverter's input moved to `n0`,
/// and the first's output left open. The oracle compares the drawing with
/// what the Verilog means flat (`flatten`, each instance in turn), so a
/// hierarchical reference must equal flattening it.
pub fn fixturesInto(arena: Allocator, depth: Depth, out: *std.ArrayList(Fixture)) !void {
    _ = depth;
    const block = try Circuit.init(arena, 4, &.{ Dev.mos(.n, 0, 2, 1), Dev.mos(.p, 0, 3, 1) });
    const top = try withNet(arena, try Circuit.init(arena, 4, &.{}), "m");
    // The chain, flat: `u0` from n0 to m, `u1` on `second`. Every net of
    // the block is a port, so flattening names no inner net.
    const drawn = try chain(arena, &top, &block, .{ 0, 4, 2, 3 }, .{ 4, 1, 2, 3 });
    var library: std.ArrayList(u8) = .empty;
    try library.appendSlice(arena, "* generated by tests/exhaustive/lvs.rs\n");
    try circuit.subcktInto(arena, &library, "BLK", &block, &.{ 0, 1 });
    try library.appendSlice(arena, ".ends\n");
    const open = try withNet(arena, top, "u0.n1");
    const cases = [_]struct { []const u8, []const u8, Circuit }{
        .{ "by_name_and_in_order", "  wire m;\n  BLK u0 (.n1(m), .n0(n0), .n2(n2), .n3(n3), .SUB);\n  BLK u1 (m, n1, n2, n3 SUB);\n", try chain(arena, &top, &block, .{ 0, 4, 2, 3 }, .{ 4, 1, 2, 3 }) },
        .{ "bus_and_assign", "  wire [1:0] w;\n  assign w[0] = n0;\n  BLK u0 (.n0(w[0]), .n1(w[1]), .n2(n2), .n3(n3), .SUB);\n  BLK u1 ({w[1]}, n1, n2, n3 SUB);\n", try chain(arena, &top, &block, .{ 0, 4, 2, 3 }, .{ 4, 1, 2, 3 }) },
        .{ "second_input_moved", "  wire m;\n  BLK u0 (.n0(n0), .n1(m), .n2(n2), .n3(n3), .SUB);\n  BLK u1 (n0, n1, n2, n3 SUB);\n", try chain(arena, &top, &block, .{ 0, 4, 2, 3 }, .{ 0, 1, 2, 3 }) },
        .{ "first_output_open", "  wire m;\n  BLK u0 (.n0(n0), .n1(), .n2(n2), .n3(n3), .SUB);\n  BLK u1 (.n0(m), .n1(n1), .n2(n2), .n3(n3), .SUB);\n", try chain(arena, &open, &block, .{ 0, 5, 2, 3 }, .{ 4, 1, 2, 3 }) },
    };
    for (cases) |case| {
        var f: Fixture = .init(try std.fmt.allocPrint(arena, "lvs/verilog/{s}", .{case[0]}), &.{"LVS-075"}, circuit.full_deck, lf.lvs);
        f.layout = try circuit.draw(arena, &drawn);
        try f.claim(arena, .{ .lvs = try oracle.equivalent(arena, &drawn, &case[2]) });
        f.reference = library.items;
        f.verilog = try arena.dupe([]const u8, &.{try module(arena, case[1])});
        try out.append(arena, f);
    }
}

// ---- private ----

/// `c` with one more net, `name`, not a port.
fn withNet(arena: Allocator, c: Circuit, name: []const u8) !Circuit {
    var out = try c.clone(arena);
    out.names = try std.mem.concat(arena, []const u8, &.{ c.names, &.{name} });
    out.ports = try std.mem.concat(arena, bool, &.{ c.ports, &.{false} });
    return out;
}

/// `top` with `block` flattened in on `first`, then again on `second`.
fn chain(arena: Allocator, top: *const Circuit, block: *const Circuit, first: [4]usize, second: [4]usize) !Circuit {
    const once = try circuit.flatten(arena, top, block, &first);
    return circuit.flatten(arena, &once, block, &second);
}

/// The Verilog module `TOP` over `body`, with no `SUB` connection.
fn module(arena: Allocator, body: []const u8) ![]const u8 {
    const no_sub = try std.mem.replaceOwned(u8, arena, body, ", .SUB", "");
    const closed = try std.mem.replaceOwned(u8, arena, no_sub, " SUB)", ")");
    return std.fmt.allocPrint(arena, "module TOP (n0, n1, n2, n3);\n  inout n0, n1, n2, n3;\n{s}endmodule\n", .{closed});
}

test "every verilog top fixture holds" {
    // Oracle: the oracle's verdict on the drawing against what each Verilog
    // top means flat (LVS-075 above): two inverters chained, by name, in
    // order, through a bus, and two faults.
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    var fixtures: std.ArrayList(Fixture) = .empty;
    try fixturesInto(arena.allocator(), .merge, &fixtures);
    try harness.checkAll(fixtures.items);
}
