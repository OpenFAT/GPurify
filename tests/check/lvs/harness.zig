//! A circuit drawn as a real layout and written as a SPICE or Spectre
//! reference, then run through what the engine's load, extract and LVS
//! stages do for a flat layout: GDSII written and read back, layers
//! derived, labels bound, nets and devices extracted, ports bound, both
//! sides projected and compared. In: an oracle `Circuit` to draw and the
//! reference text. Out: whether LVS matched. Ported from
//! tests/exhaustive/lvs.rs (`MOS_DECK`, `draw`, `draw_mos`, `stub`,
//! `card`, `spice`, `spice_ordered`, `spectre`) and the LVS path of
//! tests/exhaustive/harness.rs `run` (src/engine/pipeline.rs `extract`,
//! run.rs `run_lvs`, `param_names`).
//!
//! Contents:
//! - `pub const mos_deck`
//! - `pub fn spiceInto(gpa: Allocator, c: *const Circuit, reversed: bool, out: *std.ArrayList(u8)) !void`
//! - `pub fn spectreInto(gpa: Allocator, c: *const Circuit, out: *std.ArrayList(u8)) !void`
//! - `pub fn lvsMatches(gpa: Allocator, drawn: *const Circuit, reference: []const u8, spectre: bool) !bool`

const std = @import("std");
const Allocator = std.mem.Allocator;
const geom = @import("geom");
const StrTable = geom.StrTable;
const GeometryStore = geom.GeometryStore;
const Grid = geom.Grid;
const ingest = @import("ingest");
const deck = ingest.deck;
const check = @import("check");
const lvs = check.lvs;
const topology = check.topology;
const testgen = @import("testgen");
const oracle = @import("oracle.zig");
const Circuit = oracle.Circuit;
const Dev = oracle.Dev;

/// `nmos` and `pmos` only: the deck of the enumeration.
pub const mos_deck =
    \\grid 1nm
    \\layer diff = gds(1, 0)
    \\layer poly = gds(2, 0)
    \\layer nsdm = gds(3, 0)
    \\layer psdm = gds(4, 0)
    \\layer hvt = gds(5, 0)
    \\layer cont = gds(8, 0)
    \\layer met1 = gds(10, 0)
    \\layer via1 = gds(11, 0)
    \\layer met2 = gds(12, 0)
    \\layer met2_label = gds(12, 5)
    \\layer diff_active = diff not poly
    \\layer gate = poly and diff
    \\layer gate_n = gate and nsdm
    \\layer gate_nl = gate_n not hvt
    \\layer gate_p = gate and psdm
    \\connect conductors [diff_active, poly, met1, met2]
    \\connect touch_within_layer
    \\connect via cont [diff_active, met1]
    \\connect via cont [poly, met1]
    \\connect via via1 [met1, met2]
    \\connect label met2_label names met2
    \\device mos gate_nl model "nmos" terminals [poly, diff_active, diff_active]
    \\device mos gate_p model "pmos" terminals [poly, diff_active, diff_active]
    \\lvs tolerance default relative 2%
    \\
;

/// Columns are this far apart; each device sits in its own.
const pitch: i64 = 3000;

/// The lowest met2 track; every device fits below it.
const track0: i64 = 4000;

/// Track spacing; tracks are 200 nm tall.
const track_pitch: i64 = 400;

/// Source and drain diffusion length.
const sd_length: i64 = 500;

/// The deck layers the drawer draws on.
const Layers = struct {
    diff: u16,
    poly: u16,
    nsdm: u16,
    psdm: u16,
    cont: u16,
    met1: u16,
    via1: u16,
    met2: u16,
    met2_label: u16,

    fn of(layers: *const deck.LayerTable, strings: *const StrTable) Layers {
        var out: Layers = undefined;
        inline for (@typeInfo(Layers).@"struct".field_names) |f| @field(out, f) = @backingInt(layers.id(strings, f).?);
        return out;
    }
};

/// `c` as one subcircuit `TOP`, cards in order or reversed.
pub fn spiceInto(gpa: Allocator, c: *const Circuit, reversed: bool, out: *std.ArrayList(u8)) !void {
    out.clearRetainingCapacity();
    try out.appendSlice(gpa, "* generated by tests/exhaustive/lvs.rs\n.subckt TOP");
    try ports(gpa, c, out);
    for (0..c.ndevs) |k| {
        const i = if (reversed) c.ndevs - 1 - k else k;
        try card(gpa, out, i, &c.devs[i], false);
    }
    try out.appendSlice(gpa, ".ends\n");
}

/// `c` as one Spectre subcircuit `TOP` (LVS-071): every model gets a
/// `model` card naming its master (F97).
pub fn spectreInto(gpa: Allocator, c: *const Circuit, out: *std.ArrayList(u8)) !void {
    out.clearRetainingCapacity();
    try out.appendSlice(gpa, "// generated by tests/exhaustive/lvs.rs\nmodel nmos bsim4\nmodel pmos bsim4\nmodel nmos_hvt bsim4\nmodel nmosb bsim4\nmodel rpoly resistor\nmodel cmim capacitor\nmodel dpn diode\nmodel npn bjt\nmodel spiral inductor\nsubckt TOP");
    try ports(gpa, c, out);
    for (c.devices(), 0..) |*d, i| try card(gpa, out, i, d, true);
    try out.appendSlice(gpa, "ends TOP\n");
}

/// Draws `drawn`, reads `reference` (Spectre when `spectre`), and runs the
/// engine's LVS path; whether the verdict is a match. A stage that refuses
/// is an error.
pub fn lvsMatches(gpa: Allocator, drawn: *const Circuit, reference: []const u8, spectre: bool) !bool {
    var arena: std.heap.ArenaAllocator = .init(gpa);
    defer arena.deinit();
    var strings: StrTable = .empty;
    defer strings.deinit(gpa);
    const grid = try Grid.init(1000);
    var deck_diag: deck.Diag = .{};
    const dk = try deck.parseDeck(arena.allocator(), gpa, mos_deck, grid, &strings, &deck_diag);

    // Load: GDSII written and read back, layers derived, labels bound.
    var bytes: std.ArrayList(u8) = .empty;
    defer bytes.deinit(gpa);
    try drawInto(gpa, drawn, &dk.layers, &strings, &bytes);
    var gds_diag: ingest.gds.Diagnostic = .{};
    var lib = try ingest.gds.Library.parse(gpa, bytes.items, &strings, &gds_diag);
    defer lib.deinit(gpa);
    var store: GeometryStore = .empty;
    defer store.deinit(gpa);
    var provenance: ingest.Provenance = .{};
    defer provenance.deinit(gpa);
    var tags: std.ArrayList(u64) = .empty;
    defer tags.deinit(gpa);
    try ingest.layout.flattenInto(gpa, &lib, &dk.layers, &strings, .reject, .all, &store, &provenance, &tags, &gds_diag);
    try ingest.layout.deriveLayersInto(gpa, &store, &dk.layers, &provenance, &strings, tags.items);
    var unplaced: ingest.provenance.PlacedLabel = undefined;
    try ingest.resolveLabels(gpa, &provenance, &store, &dk.connectivity, &unplaced);
    var net_diag: ingest.netlist.Diagnostic = .{};
    var read = if (spectre) try ingest.netlist.readSpectre(gpa, reference, &strings, &dk.devices, &net_diag) else try ingest.netlist.readSpice(gpa, reference, &strings, &dk.devices, &net_diag);
    defer read.deinit(gpa);
    const read_top = (try read.top(gpa)) orelse return error.TestNoTop;
    var flat = try ingest.netlist.flattenTop(gpa, &read, read_top, &strings, &net_diag);
    defer flat.deinit(gpa);

    // Extract.
    var channel_diag: topology.channel.ChannelDiagnostic = undefined;
    try topology.refuseConductingChannels(gpa, &store, &dk.connectivity, &dk.devices, &channel_diag);
    var nets: topology.NetTable = .{};
    defer nets.deinit(gpa);
    try topology.extractNetsInto(gpa, &store, &dk.connectivity, &nets);
    var devices: topology.DeviceTable = .{};
    defer devices.deinit(gpa);
    try topology.recogniseInto(gpa, &store, &nets, &dk.devices, &devices);
    var port_table: topology.PortTable = .{};
    defer port_table.deinit(gpa);
    try topology.bindPortsInto(gpa, &nets, provenance.labels(), &port_table);

    // LVS.
    try lvs.internRuleIds(gpa, &strings);
    var layout: lvs.Graph = .{};
    defer layout.deinit(gpa);
    try lvs.fromLayoutInto(gpa, &nets, &devices, &port_table, &strings, grid, &layout);
    const top = (try flat.top(gpa)) orelse return error.TestNoTop;
    var ref_graph: lvs.Graph = .{};
    defer ref_graph.deinit(gpa);
    try lvs.fromReferenceInto(gpa, &flat, top, &ref_graph);
    var traced: lvs.Traced = .{};
    defer traced.deinit(gpa);
    const options: lvs.CompareOptions = .{ .param_tolerance = dk.lvs.default_tolerance.?, .params = paramNames(&strings) };
    try lvs.compareTraced(gpa, &layout, &ref_graph, options, &dk.lvs, &traced);
    return switch (traced.verdict) {
        .match => true,
        .mismatch => false,
        .inconclusive => error.TestInconclusive,
    };
}

// ---- private ----

/// The run's SPICE names of the sizes, diffusions and values
/// (run.rs `param_names`).
fn paramNames(strings: *const StrTable) lvs.ParamNames {
    const n = struct {
        fn get(s: *const StrTable, name: []const u8) ?geom.StrId {
            return s.get(name);
        }
    }.get;
    return .{
        .width = n(strings, "w"),
        .length = n(strings, "l"),
        .fingers = n(strings, "nf"),
        .multiplier = n(strings, "m"),
        .diffusion = .{ n(strings, "as"), n(strings, "ad"), n(strings, "ps"), n(strings, "pd") },
        .values = .{ n(strings, "r"), n(strings, "c"), n(strings, "area"), n(strings, "perim"), n(strings, "ae"), n(strings, "pe") },
        .inductance = n(strings, "ind"),
        .stress = .{ n(strings, "sa"), n(strings, "sb") },
    };
}

fn ports(gpa: Allocator, c: *const Circuit, out: *std.ArrayList(u8)) !void {
    for (0..c.nets) |k| if (c.ports[k]) try out.print(gpa, " n{d}", .{k});
    try out.append(gpa, '\n');
}

/// One MOS card; a three-terminal MOS's bulk written as its source (the
/// deck extracts none, so the comparison drops it).
fn card(gpa: Allocator, out: *std.ArrayList(u8), index: usize, d: *const Dev, spectre: bool) !void {
    std.debug.assert(d.model.isMos());
    const open = if (spectre) "(" else "";
    const close = if (spectre) ")" else "";
    try out.print(gpa, "M{d} {s}n{d} n{d} n{d} n{d}{s} {s}", .{ index, open, d.pins[2], d.pins[0], d.pins[1], d.pins[1], close, d.model.name() });
    if (d.writes_w) try out.print(gpa, " w={d}n", .{d.w});
    if (d.writes_l) try out.print(gpa, " l={d}n", .{d.l});
    if (d.m != 1) try out.print(gpa, " m={d}", .{d.m});
    try out.append(gpa, '\n');
}

/// The layout of `c` as GDSII: device `i` in column `i`, net `k` a met2
/// track labelled `n{k}` when it is a port.
fn drawInto(gpa: Allocator, c: *const Circuit, layers: *const deck.LayerTable, strings: *const StrTable, out: *std.ArrayList(u8)) !void {
    var lb: testgen.shapes.LayoutBuilder = .init(@intCast(layers.len()));
    defer lb.deinit(gpa);
    const ids = Layers.of(layers, strings);
    for (c.devices(), 0..) |*d, i| try drawMos(gpa, &lb, ids, pitch * @as(i64, @intCast(i)), d);
    const right = pitch * @as(i64, c.ndevs);
    var names: [oracle.max_nets][4]u8 = undefined;
    var labels: [oracle.max_nets]testgen.gds.Label = undefined;
    var nlabels: usize = 0;
    for (0..c.nets) |k| {
        const t = track(k);
        _ = try lb.rect(gpa, ids.met2, -1000, t, right, t + 200);
        if (!c.ports[k]) continue;
        const text = try std.fmt.bufPrint(&names[k], "n{d}", .{k});
        labels[nlabels] = .{ .layer = @fromBackingInt(ids.met2_label), .x = -900, .y = t + 100, .text = text };
        nlabels += 1;
    }
    var store: GeometryStore = .empty;
    defer store.deinit(gpa);
    var handles: testgen.shapes.Ids = .{};
    defer handles.deinit(gpa);
    try lb.finish(gpa, &store, &handles);
    try testgen.gds.writeStoreLabelled(gpa, &store, layers, labels[0..nlabels], "TOP", out);
}

fn track(net: usize) i64 {
    return track0 + track_pitch * @as(i64, @intCast(net));
}

/// A met1 stub from `y0` up to `net`'s track over `x0..x1`, the via there.
fn stub(gpa: Allocator, lb: *testgen.shapes.LayoutBuilder, ids: Layers, x0: i64, x1: i64, y0: i64, net: u8) !void {
    const t = track(net);
    _ = try lb.rect(gpa, ids.met1, x0, y0, x1, t + 200);
    _ = try lb.rect(gpa, ids.via1, x0, t, x1, t + 200);
}

/// Poly across diffusion: the channel `l` along x, `w` along y, so the
/// recogniser measures exactly `w` and `l`. Source left, drain right, each
/// contacted near the bottom; the gate contacted above the diffusion.
fn drawMos(gpa: Allocator, lb: *testgen.shapes.LayoutBuilder, ids: Layers, x0: i64, d: *const Dev) !void {
    const w = d.w;
    const l = d.l;
    std.debug.assert(w >= 500 and w <= track0 - 1000);
    const xd = x0 + sd_length + l;
    _ = try lb.rect(gpa, ids.diff, x0, 0, xd + sd_length, w);
    _ = try lb.rect(gpa, ids.poly, x0 + sd_length, -200, xd, w + 500);
    const implant = switch (d.model) {
        .n => ids.nsdm,
        .p => ids.psdm,
        .r, .c, .d, .q => unreachable, // the enumeration draws MOS only
    };
    _ = try lb.rect(gpa, implant, x0 - 200, -300, xd + sd_length + 200, w + 200);
    _ = try lb.rect(gpa, ids.cont, x0 + 100, 100, x0 + 400, 400);
    _ = try lb.rect(gpa, ids.cont, xd + 100, 100, xd + 400, 400);
    _ = try lb.rect(gpa, ids.cont, x0 + sd_length, w + 250, xd, w + 400);
    try stub(gpa, lb, ids, x0 + 100, x0 + 400, 100, d.pins[1]);
    try stub(gpa, lb, ids, xd + 100, xd + 400, 100, d.pins[2]);
    try stub(gpa, lb, ids, x0 + sd_length, xd, w + 250, d.pins[0]);
}
